# ==================== 辅助函数 ====================

def get_prompt_by_subject(prompt_type: str, subject: str) -> str:
    """
    根据学科和prompt类型获取对应的prompt模板
    
    Args:
        prompt_type: prompt类型，可选值：'unit', 'daily', 'assessment'
        subject: 学科名称，如'英语', 'English', '数学', 'Math'等
    
    Returns:
        对应的prompt模板字符串
    
    Examples:
        >>> get_prompt_by_subject('unit', '英语')
        返回 GENERIC_UNIT_PROMPT_ENGLISH
        
        >>> get_prompt_by_subject('daily', 'Math')
        返回 DAILY_PRACTICE_PROMPT_MATH
    """
    # 标准化学科名称
    subject_lower = subject.lower()
    is_english = any(keyword in subject_lower for keyword in ['英语', 'english'])
    is_math = any(keyword in subject_lower for keyword in ['数学', 'math', '数'])
    
    # 根据类型和学科返回对应的prompt
    if prompt_type == 'unit':
        if is_math:
            return GENERIC_UNIT_PROMPT_MATH
        else:
            return GENERIC_UNIT_PROMPT_ENGLISH  # 默认英语
            
    elif prompt_type == 'daily':
        if is_math:
            return DAILY_PRACTICE_PROMPT_MATH
        else:
            return DAILY_PRACTICE_PROMPT_ENGLISH  # 默认英语
            
    elif prompt_type == 'assessment':
        if is_math:
            return ASSESSMENT_GENERATION_PROMPT_MATH
        else:
            return ASSESSMENT_GENERATION_PROMPT_ENGLISH  # 默认英语
    
    # 如果类型不匹配，返回默认的英语单元prompt
    return GENERIC_UNIT_PROMPT_ENGLISH
